import { PhoneMessageSubscriber } from '../../../../public/typings/subscription'
import {
  PhoneMessageBatchResultEntity,
  SealedPhoneMessageEntity,
  SortOrderEntity,
} from './phoneMessageEntity'

/**
 * Input for `PhoneMessageService.listForPhoneNumberId` method.
 *
 * @interface ListPhoneMessagesForPhoneNumberIdInput
 * @property {string} phoneNumberId Unique identifier of the phone number whose messages to list.
 * @property {SortOrderEntity} sortOrder Order of the messages.
 * @property {number} limit Maximum number of items per page.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneMessagesForPhoneNumberIdInput {
  phoneNumberId: string
  sortOrder?: SortOrderEntity
  limit?: number
  nextToken?: string
}

/**
 * Input for `PhoneMessageService.listForConversationId` method.
 *
 * @interface ListPhoneMessagesForConversationIdInput
 * @property {string} conversationId Unique identifier of the conversation whose messages to list.
 * @property {SortOrderEntity} sortOrder Order of the messages.
 * @property {number} limit Maximum number of items per page.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneMessagesForConversationIdInput {
  conversationId: string
  sortOrder?: SortOrderEntity
  limit?: number
  nextToken?: string
}

/**
 * Output for the `PhoneMessageService` list methods.
 *
 * @interface ListPhoneMessagesOutput
 * @property {SealedPhoneMessageEntity[]} phoneMessages The sealed phone messages retrieved in
 *  this query.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneMessagesOutput {
  phoneMessages: SealedPhoneMessageEntity[]
  nextToken?: string
}

/**
 * Input for `PhoneMessageService.update` method.
 *
 * @interface UpdatePhoneMessagesInput
 * @property {string[]} ids Unique identifiers of the messages to update.
 * @property {boolean} seen The read state to set.
 */
export interface UpdatePhoneMessagesInput {
  ids: string[]
  seen: boolean
}

/**
 * Input for `PhoneMessageService.subscribe` method.
 *
 * @interface SubscribeToPhoneMessagesInput
 * @property {string} subscriptionId A unique identifier for this subscription.
 * @property {string} owner The identifier of the owner to subscribe for.
 * @property {PhoneMessageSubscriber} subscriber The subscriber to receive events.
 */
export interface SubscribeToPhoneMessagesInput {
  subscriptionId: string
  owner: string
  subscriber: PhoneMessageSubscriber
}

/**
 * Core entity representation of a phone message service used in business logic.
 * Used to retrieve, update and delete the caller's phone messages.
 *
 * @interface PhoneMessageService
 */
export interface PhoneMessageService {
  /**
   * Retrieve one of the caller's phone messages, still sealed.
   *
   * @param {string} id The unique identifier of the phone message to retrieve.
   * @returns {SealedPhoneMessageEntity | undefined} The sealed phone message, or undefined when
   *  no message with the ID belongs to the caller.
   */
  get(id: string): Promise<SealedPhoneMessageEntity | undefined>

  /**
   * Retrieve a page of a phone number's messages, still sealed.
   *
   * @param {ListPhoneMessagesForPhoneNumberIdInput} input The phone number and paging parameters.
   * @returns {ListPhoneMessagesOutput} The page of sealed phone messages and its next token.
   */
  listForPhoneNumberId(
    input: ListPhoneMessagesForPhoneNumberIdInput,
  ): Promise<ListPhoneMessagesOutput>

  /**
   * Retrieve a page of a conversation's messages, still sealed.
   *
   * @param {ListPhoneMessagesForConversationIdInput} input The conversation and paging parameters.
   * @returns {ListPhoneMessagesOutput} The page of sealed phone messages and its next token.
   */
  listForConversationId(
    input: ListPhoneMessagesForConversationIdInput,
  ): Promise<ListPhoneMessagesOutput>

  /**
   * Delete a batch of the caller's phone messages.
   *
   * @param {string[]} ids The unique identifiers of the messages to delete.
   * @returns {PhoneMessageBatchResultEntity} The deleted and not deleted messages.
   */
  delete(ids: string[]): Promise<PhoneMessageBatchResultEntity>

  /**
   * Change the read state of a batch of the caller's phone messages.
   *
   * @param {UpdatePhoneMessagesInput} input The messages to update and the state to set.
   * @returns {PhoneMessageBatchResultEntity} The updated and not updated messages.
   */
  update(
    input: UpdatePhoneMessagesInput,
  ): Promise<PhoneMessageBatchResultEntity>

  /**
   * Subscribe to phone message events.
   *
   * @param {SubscribeToPhoneMessagesInput} input Parameters used to subscribe to phone message
   *  events.
   */
  subscribe(input: SubscribeToPhoneMessagesInput): Promise<void>

  /**
   * Unsubscribe from phone message events.
   *
   * @param {string} subscriptionId The unique identifier of the subscription to unsubscribe from.
   */
  unsubscribe(subscriptionId: string): void
}
