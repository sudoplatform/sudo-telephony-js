import { PublicKeyFormat } from '@sudoplatform/sudo-common'
import { PhoneNumberSubscriber } from '../../../../public/typings/subscription'
import { PhoneNumberEntity } from './phoneNumberEntity'

/**
 * The public half of the key pair whose public key the service registers to seal a
 * phone number's messages.
 *
 * @interface ProvisionPhoneNumberPublicKey
 * @property {string} keyId Unique identifier of the key pair.
 * @property {string} algorithm The algorithm the service must seal messages with.
 * @property {PublicKeyFormat} keyFormat The encoding of the public key, which the service
 *  needs in order to read it.
 * @property {string} publicKey The Base64 encoded public key.
 */
export interface ProvisionPhoneNumberPublicKey {
  keyId: string
  algorithm: string
  keyFormat: PublicKeyFormat
  publicKey: string
}

/**
 * Input for `PhoneNumberService.provision` method.
 *
 * @interface ProvisionPhoneNumberInput
 * @property {string} searchId Unique identifier of the search the number came from.
 * @property {string} phoneNumber The number to provision, in E.164 format.
 * @property {ProvisionPhoneNumberPublicKey} key The public key the service registers to seal
 *  the number's messages.
 * @property {string} ownershipProofToken Proof that the caller owns the Sudo the number will
 *  belong to.
 * @property {string} clientRefId Client-supplied reference that makes the request idempotent.
 */
export interface ProvisionPhoneNumberInput {
  searchId: string
  phoneNumber: string
  key: ProvisionPhoneNumberPublicKey
  ownershipProofToken?: string
  clientRefId?: string
}

/**
 * Input for `PhoneNumberService.list` method.
 *
 * @interface ListPhoneNumbersInput
 * @property {number} limit Maximum number of items per page. When undefined the service
 *  applies its own default.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneNumbersInput {
  limit?: number
  nextToken?: string
}

/**
 * Input for `PhoneNumberService.listForSudoId` method.
 *
 * @interface ListPhoneNumbersForSudoIdInput
 * @property {string} sudoId Unique identifier of the Sudo whose phone numbers to list.
 */
export interface ListPhoneNumbersForSudoIdInput extends ListPhoneNumbersInput {
  sudoId: string
}

/**
 * Output for `PhoneNumberService.list` and `PhoneNumberService.listForSudoId` methods.
 *
 * @interface ListPhoneNumbersOutput
 * @property {PhoneNumberEntity[]} phoneNumbers The list of phone numbers retrieved in this query.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneNumbersOutput {
  phoneNumbers: PhoneNumberEntity[]
  nextToken?: string
}

/**
 * Input for `PhoneNumberService.subscribe` method.
 *
 * @interface SubscribeToPhoneNumbersInput
 * @property {string} subscriptionId A unique identifier for this subscription.
 * @property {string} owner The identifier of the owner to subscribe for.
 * @property {PhoneNumberSubscriber} subscriber The subscriber to receive events.
 */
export interface SubscribeToPhoneNumbersInput {
  subscriptionId: string
  owner: string
  subscriber: PhoneNumberSubscriber
}

/**
 * Core entity representation of a phone number service used in business logic.
 * Used to perform CRUD operations for provisioned phone numbers.
 *
 * @interface PhoneNumberService
 */
export interface PhoneNumberService {
  /**
   * Provision a phone number from one of the caller's searches.
   *
   * @param {ProvisionPhoneNumberInput} input The number to provision and the key to seal its
   *  messages with.
   * @returns {PhoneNumberEntity} The phone number, which starts in
   *  `PhoneNumberStateEntity.Provisioning`.
   */
  provision(input: ProvisionPhoneNumberInput): Promise<PhoneNumberEntity>

  /**
   * Release one of the caller's phone numbers.
   *
   * @param {string} id The unique identifier of the phone number to release.
   * @returns {PhoneNumberEntity} The phone number in `PhoneNumberStateEntity.Released`.
   */
  deprovision(id: string): Promise<PhoneNumberEntity>

  /**
   * Retrieve one of the caller's phone numbers in any state.
   *
   * @param {string} id The unique identifier of the phone number to retrieve.
   * @returns {PhoneNumberEntity | undefined} The phone number, or undefined when no phone number
   *  with the ID belongs to the caller.
   */
  get(id: string): Promise<PhoneNumberEntity | undefined>

  /**
   * Retrieve a page of the caller's phone numbers.
   *
   * @param {ListPhoneNumbersInput} input Parameters used to list phone numbers.
   * @returns {ListPhoneNumbersOutput} The page of phone numbers and its next token.
   */
  list(input: ListPhoneNumbersInput): Promise<ListPhoneNumbersOutput>

  /**
   * Retrieve a page of the caller's phone numbers that a Sudo owns.
   *
   * @param {ListPhoneNumbersForSudoIdInput} input The Sudo and paging parameters.
   * @returns {ListPhoneNumbersOutput} The page of phone numbers and its next token.
   */
  listForSudoId(
    input: ListPhoneNumbersForSudoIdInput,
  ): Promise<ListPhoneNumbersOutput>

  /**
   * Subscribe to phone number change events.
   *
   * @param {SubscribeToPhoneNumbersInput} input Parameters used to subscribe to phone number
   *  change events.
   */
  subscribe(input: SubscribeToPhoneNumbersInput): Promise<void>

  /**
   * Unsubscribe from phone number change events.
   *
   * @param {string} subscriptionId The unique identifier of the subscription to unsubscribe from.
   */
  unsubscribe(subscriptionId: string): void
}
