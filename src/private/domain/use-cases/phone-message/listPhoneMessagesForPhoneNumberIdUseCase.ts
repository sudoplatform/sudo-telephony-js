import { DefaultLogger, Logger } from '@sudoplatform/sudo-common'
import { SortOrderEntity } from '../../entities/phone-message/phoneMessageEntity'
import { PhoneMessageService } from '../../entities/phone-message/phoneMessageService'
import { PhoneMessageUnsealer } from '../../entities/phone-message/phoneMessageUnsealer'
import { ListPhoneMessagesUseCaseOutput } from './listPhoneMessagesOutput'

/**
 * Input for `ListPhoneMessagesForPhoneNumberIdUseCase`.
 *
 * @interface ListPhoneMessagesForPhoneNumberIdUseCaseInput
 * @property {string} phoneNumberId Unique identifier of the phone number whose messages to list.
 * @property {SortOrderEntity} sortOrder Order of the messages.
 * @property {number} limit Maximum number of items per page.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneMessagesForPhoneNumberIdUseCaseInput {
  phoneNumberId: string
  sortOrder?: SortOrderEntity
  limit?: number
  nextToken?: string
}

/**
 * Application business logic for listing a phone number's messages and making them
 * readable. The sealing key is resolved once for the page.
 */
export class ListPhoneMessagesForPhoneNumberIdUseCase {
  private readonly log: Logger

  public constructor(
    private readonly phoneMessageService: PhoneMessageService,
    private readonly unsealer: PhoneMessageUnsealer,
  ) {
    this.log = new DefaultLogger(this.constructor.name)
  }

  async execute(
    input: ListPhoneMessagesForPhoneNumberIdUseCaseInput,
  ): Promise<ListPhoneMessagesUseCaseOutput> {
    this.log.debug(this.constructor.name, { input })
    const page = await this.phoneMessageService.listForPhoneNumberId({
      phoneNumberId: input.phoneNumberId,
      sortOrder: input.sortOrder,
      limit: input.limit,
      nextToken: input.nextToken,
    })
    const result = await this.unsealer.unseal(
      input.phoneNumberId,
      page.phoneMessages,
    )
    return {
      phoneMessages: result.unsealed,
      failed: result.failed,
      nextToken: page.nextToken,
    }
  }
}
