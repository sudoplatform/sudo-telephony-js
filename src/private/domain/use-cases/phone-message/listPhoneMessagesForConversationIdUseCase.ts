import { DefaultLogger, Logger } from '@sudoplatform/sudo-common'
import { SortOrderEntity } from '../../entities/phone-message/phoneMessageEntity'
import { PhoneMessageService } from '../../entities/phone-message/phoneMessageService'
import { PhoneMessageUnsealer } from '../../entities/phone-message/phoneMessageUnsealer'
import { ListPhoneMessagesUseCaseOutput } from './listPhoneMessagesOutput'

/**
 * Input for `ListPhoneMessagesForConversationIdUseCase`.
 *
 * @interface ListPhoneMessagesForConversationIdUseCaseInput
 * @property {string} conversationId Unique identifier of the conversation whose messages to list.
 * @property {SortOrderEntity} sortOrder Order of the messages.
 * @property {number} limit Maximum number of items per page.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneMessagesForConversationIdUseCaseInput {
  conversationId: string
  sortOrder?: SortOrderEntity
  limit?: number
  nextToken?: string
}

/**
 * Application business logic for listing a conversation's messages and making them
 * readable.
 *
 * A conversation belongs to one phone number, which the page's messages identify, so
 * the sealing key is resolved from the first message.
 */
export class ListPhoneMessagesForConversationIdUseCase {
  private readonly log: Logger

  public constructor(
    private readonly phoneMessageService: PhoneMessageService,
    private readonly unsealer: PhoneMessageUnsealer,
  ) {
    this.log = new DefaultLogger(this.constructor.name)
  }

  async execute(
    input: ListPhoneMessagesForConversationIdUseCaseInput,
  ): Promise<ListPhoneMessagesUseCaseOutput> {
    this.log.debug(this.constructor.name, { input })
    const page = await this.phoneMessageService.listForConversationId({
      conversationId: input.conversationId,
      sortOrder: input.sortOrder,
      limit: input.limit,
      nextToken: input.nextToken,
    })
    const phoneNumberId = page.phoneMessages[0]?.phoneNumberId
    if (!phoneNumberId) {
      return { phoneMessages: [], failed: [], nextToken: page.nextToken }
    }
    const result = await this.unsealer.unseal(phoneNumberId, page.phoneMessages)
    return {
      phoneMessages: result.unsealed,
      failed: result.failed,
      nextToken: page.nextToken,
    }
  }
}
