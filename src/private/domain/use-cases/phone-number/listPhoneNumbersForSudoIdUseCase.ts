import { DefaultLogger, Logger } from '@sudoplatform/sudo-common'
import {
  ListPhoneNumbersOutput,
  PhoneNumberService,
} from '../../entities/phone-number/phoneNumberService'

/**
 * Input for `ListPhoneNumbersForSudoIdUseCase`.
 *
 * @interface ListPhoneNumbersForSudoIdUseCaseInput
 * @property {string} sudoId Unique identifier of the Sudo whose phone numbers to list.
 * @property {number} limit Maximum number of items per page.
 * @property {string} nextToken A token generated by a previous call. This allows for pagination.
 */
export interface ListPhoneNumbersForSudoIdUseCaseInput {
  sudoId: string
  limit?: number
  nextToken?: string
}

/**
 * Application business logic for listing the caller's phone numbers that a Sudo owns.
 */
export class ListPhoneNumbersForSudoIdUseCase {
  private readonly log: Logger

  public constructor(private readonly phoneNumberService: PhoneNumberService) {
    this.log = new DefaultLogger(this.constructor.name)
  }

  async execute(
    input: ListPhoneNumbersForSudoIdUseCaseInput,
  ): Promise<ListPhoneNumbersOutput> {
    this.log.debug(this.constructor.name, { input })
    return await this.phoneNumberService.listForSudoId({
      sudoId: input.sudoId,
      limit: input.limit,
      nextToken: input.nextToken,
    })
  }
}
